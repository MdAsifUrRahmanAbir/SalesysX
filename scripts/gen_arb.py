def write_arb(path, locale, values):
    data = {"@@locale": locale}
    for key, (en_value, placeholders) in ENTRIES.items():
        value = values[key] if values is not None else en_value
        data[key] = value
        if placeholders:
            meta = {"placeholders": {name: {"type": typ} for name, typ in placeholders.items()}}
            data[f"@{key}"] = meta
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print(f"wrote {path} ({len(values) if values else len(ENTRIES)} keys)")


